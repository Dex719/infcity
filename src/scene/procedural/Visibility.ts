/**
 * Стороны, невидимые при фиксированной камере (design D13, FR-18.1).
 *
 * Камера не вращается: `CameraRig` ставит её в `target + CAMERA.OFFSET (80, h, 80)` и смотрит
 * в `target`, ни панорамирование, ни колесо направление не меняют. Направление взгляда в
 * плоскости XZ — 225°, горизонтальный полуугол при `FOV` 30 — около 26°, поэтому у всех лучей
 * кадра обе компоненты (x, z) отрицательны. Грань с нормалью −X даёт `ray · n = −ray.x > 0` —
 * всегда задняя; то же для −Z. Значит геометрию, прижатую к сторонам −X и −Z, можно не строить.
 */
export interface HiddenSides {
  /** Знак локальной оси X, которая смотрит в мировой −X: эта сторона не видна. */
  readonly x: 1 | -1;
  /** Знак локальной оси Z, которая смотрит в мировой −Z: эта сторона не видна. */
  readonly z: 1 | -1;
}

/** Скрытые стороны в системе чанка (дороги и ЛРТ не поворачиваются). */
export const CHUNK_HIDDEN: HiddenSides = { x: -1, z: -1 };

/**
 * Скрытые локальные стороны квартала, повёрнутого на `rotation × 90°` (`PrefabBuilder`).
 * `makeRotationY(θ)` переносит локальный `(x, z)` в мировой `(x·cosθ + z·sinθ, −x·sinθ + z·cosθ)`,
 * отсюда таблица: 0 → (−X, −Z), 1 → (+X, −Z), 2 → (+X, +Z), 3 → (−X, +Z).
 */
export function hiddenSides(rotation: number): HiddenSides {
  const r = ((rotation % 4) + 4) % 4;
  return { x: r === 1 || r === 2 ? 1 : -1, z: r === 2 || r === 3 ? 1 : -1 };
}

/**
 * Видна ли сторона, прижатая к грани `sign` по оси: строить плоские накладки (окна, ленты
 * остекления) имеет смысл только на видимых сторонах. Выступающие объёмы — козырьки, балконы,
 * крыльца — строятся всегда: они читаются в силуэте сбоку.
 */
export function isVisibleSide(hidden: HiddenSides, axis: 'x' | 'z', sign: 1 | -1): boolean {
  return hidden[axis] !== sign;
}
